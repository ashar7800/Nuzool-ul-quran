# 1. Update surahs.json & surahs.js
with open('data/surahs.json', 'r', encoding='utf-8') as f:
    surahs = json.load(f)

for s in surahs:
    num = s['surahNumber']
    s['themeUrdu'] = THEME_URDU_MAP.get(num, f"{s.get('nameAr', '')} — دعوت و ہدایت")

with open('data/surahs.json', 'w', encoding='utf-8') as f:
    json.dump(surahs, f, ensure_ascii=False, indent=2)

with open('data/surahs.js', 'w', encoding='utf-8') as f:
    f.write('// Complete 114 Surahs Dataset with Urdu & Roman Themes + Lessons\n')
    f.write('window.SURAH_DATA = ')
    json.dump(surahs, f, ensure_ascii=False, indent=2)
    f.write(';\n')

print(f"Enriched {len(surahs)} surahs with themeUrdu.")

# 2. Update wahi_episodes.json & wahi_episodes.js
with open('data/wahi_episodes.json', 'r', encoding='utf-8') as f:
    eps = json.load(f)

for ep in eps:
    if not ep.get('themeUrdu'):
        ep['themeUrdu'] = ep.get('titleUrdu') or ep.get('theme')

with open('data/wahi_episodes.json', 'w', encoding='utf-8') as f:
    json.dump(eps, f, ensure_ascii=False, indent=2)

with open('data/wahi_episodes.js', 'w', encoding='utf-8') as f:
    f.write('// Complete 100% Chronological Quran Wahi Units Dataset with Urdu & Roman Themes + Lessons\n')
